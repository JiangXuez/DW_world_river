function deltaCorrectedToDW(img, angleBandName) {
  angleBandName = angleBandName || 'imga';
  var angle = img.select(angleBandName);
  var minimumDifference = angle.subtract(mainspeca[0]).abs();
  var dw = angle.multiply(0).add(spec_values[0]);

  for (var index = 1; index < mainspeca.length; index++) {
    var difference = angle.subtract(mainspeca[index]).abs();
    var isCloser = difference.lte(minimumDifference);
    dw = dw.where(isCloser, spec_values[index]);
    minimumDifference = minimumDifference.where(isCloser, difference);
  }

  return img.addBands(dw.rename('DW'), null, true);
}

function addDW(img) {
  return deltaCorrectedToDW(img, 'imga');
}

